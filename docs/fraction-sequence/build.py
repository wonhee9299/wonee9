def frac(n, d):
    return f'<span class="frac"><span class="num">{n}</span><span class="den">{d}</span></span>'

def seq(ns, ds, blank=4):
    parts = []
    for i, (n, d) in enumerate(zip(ns, ds)):
        parts.append('<span class="blank">(가)</span>' if i == blank else frac(n, d))
    return '<span class="seq">' + ',&nbsp; '.join(parts) + '</span>'

def table(headers, rows):
    h = ''.join(f'<th>{c}</th>' for c in headers)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>'

